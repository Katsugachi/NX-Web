import assert from 'node:assert/strict';
import { recentGames, rememberGame, compatibilityProblems, runtimeProblem } from '../web/shell-model.js';
import { ACTIONS, DEFAULT_BINDINGS, parseBindings, rebind, bindingKey, keyLabel, readBindings, writeBindings } from '../web/bindings.js';
import { BUILD_CORES, activeCore } from '../web/cores.js';
assert.deepEqual(BUILD_CORES.map(core=>core.id),['jit','interpreter']);
globalThis.location = {search:'?core=fused'};
assert.equal(activeCore().id,'jit','unbuilt runtime requests fall back to the bundled engine');
location.search='?core=interpreter'; assert.equal(activeCore().id,'interpreter');
assert.deepEqual(recentGames(null), []);
for (const raw of ['bad json', '{}', 'null', '[null,{}, {"name":"bad","size":-1}]']) assert.deepEqual(recentGames(raw), []);
const game = { name:'hello-world.nro', size:166085 };
assert.deepEqual(recentGames(JSON.stringify([game])), [game]);
assert.deepEqual(rememberGame([game],game), [game]);
assert.equal(rememberGame(Array.from({length:8},(_,i)=>({name:`${i}.nro`,size:0})),game).length,6);
assert.deepEqual(compatibilityProblems([]), []);
assert.equal(runtimeProblem(''), '');
assert.equal(runtimeProblem('Running'), '');
assert.match(runtimeProblem('runtime/eden.js not found'), /npm run build:engine/);
assert.match(runtimeProblem('Error: out of memory'), /Diagnostics/);
const fail = { id:'webgpu', required:true, status:'fail' };
assert.deepEqual(compatibilityProblems([fail, {required:true,status:'pass'}, {required:false,status:'warn'}]), [fail]);
assert.equal(bindingKey({code:'Slash',shiftKey:true}), 'Shift+Slash');
assert.equal(keyLabel('Shift+Slash'), '?');
assert.deepEqual(parseBindings(null), DEFAULT_BINDINGS);
for (const raw of ['invalid','null','[]','{"a":"not a key"}','{"a":"KeyK"}']) assert.deepEqual(parseBindings(raw), DEFAULT_BINDINGS);
const changed = rebind(DEFAULT_BINDINGS, 'a','KeyV');
assert.equal(changed.a,'KeyV');
assert.equal(DEFAULT_BINDINGS.a,'KeyL');
assert.deepEqual(parseBindings(JSON.stringify(changed)),changed);
assert.throws(()=>rebind(DEFAULT_BINDINGS,'a','KeyK'),/already used by B/);
assert.throws(()=>rebind(DEFAULT_BINDINGS,'notAnAction','KeyV'),/Choose/);
assert.throws(()=>rebind(DEFAULT_BINDINGS,'a','ControlLeft'),/Choose/);
assert.equal(rebind(DEFAULT_BINDINGS,'open','KeyL').open,'KeyL','library-only open may share a controller key');
assert.throws(()=>rebind(DEFAULT_BINDINGS,'open','KeyP'),/already used by Pause/);
globalThis.localStorage = { getItem:()=>{throw new Error('blocked');}, setItem:()=>{throw new Error('quota');} };
assert.deepEqual(readBindings(),DEFAULT_BINDINGS);
globalThis.window = new EventTarget();
assert.equal(writeBindings(DEFAULT_BINDINGS),false);
assert.equal(ACTIONS.filter(action=>!action.hotkey).length,25);
console.log('NX-Web shell: recents, compatibility failures, remapping, conflicts and blocked storage OK');
